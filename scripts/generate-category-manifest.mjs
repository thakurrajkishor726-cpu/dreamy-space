/**
 * Browsers can't list a directory, so the images under
 * public/images/categories/<Folder_Name>/ need a manifest.
 *
 * Folder name -> category name (underscores become spaces), matching what
 * scripts/seed_categories.py writes into the database, so the two line up.
 * Paths are URL-encoded because the filenames contain spaces.
 *
 * Runs automatically via predev/prebuild.
 */

import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, extname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SOURCE = join(ROOT, "public/images/categories");
const OUTPUT = join(ROOT, "src/data/categoryImages.js");

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

// "image copy 10.png" should follow "image copy 2.png", not precede it.
const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

if (!existsSync(SOURCE)) {
  writeFileSync(OUTPUT, "export const CATEGORY_IMAGES = [];\n");
  console.log("category manifest: source folder missing, wrote empty manifest");
  process.exit(0);
}

const categories = readdirSync(SOURCE)
  .filter((entry) => statSync(join(SOURCE, entry)).isDirectory())
  .sort(natural)
  .map((folder) => {
    const images = readdirSync(join(SOURCE, folder))
      .filter((file) => IMAGE_EXT.has(extname(file).toLowerCase()))
      .sort(natural)
      .map((file) => `/images/categories/${encodeURIComponent(folder)}/${encodeURIComponent(file)}`);

    return {
      name: folder.replace(/_/g, " ").trim(),
      folder,
      images,
    };
  })
  .filter((category) => category.images.length > 0);

const banner = `// GENERATED by scripts/generate-category-manifest.mjs — do not edit.
// Regenerate with: npm run categories:manifest
`;

writeFileSync(OUTPUT, `${banner}\nexport const CATEGORY_IMAGES = ${JSON.stringify(categories, null, 2)};\n`);

console.log(
  `category manifest: ${categories.length} categories, ` +
    `${categories.reduce((total, category) => total + category.images.length, 0)} images`,
);
